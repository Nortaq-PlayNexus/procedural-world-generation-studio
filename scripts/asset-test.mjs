import { chromium } from 'playwright';
import fs from 'node:fs';
const browser = await chromium.launch({ args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const errors = [];
page.on('pageerror', e => errors.push('PAGEERROR ' + e.message));
page.on('console', m => { if (m.type() === 'error') errors.push('CONSOLE ' + m.text().slice(0,200)); });
const client = await page.context().newCDPSession(page);
const shot = async (name) => { const { data } = await client.send('Page.captureScreenshot', { format: 'jpeg', quality: 85 }); fs.writeFileSync(name, Buffer.from(data, 'base64')); };
await page.goto('http://localhost:4173', { waitUntil: 'load' });
await page.waitForTimeout(12000);
await page.locator('select[aria-label="Render quality"]').selectOption('low').catch(()=>{});
await page.waitForTimeout(1200);
const report = {};
const readObjects = () => page.evaluate(() => (document.body.innerText.match(/OBJECTS\n([\d,]+)/)?.[1] ?? 'n/a'));
report.before = await readObjects();
await shot('reports/visual/ui-materials.jpg');
await page.getByText('Interactive editor', { exact: false }).first().click();
await page.waitForTimeout(500);
await page.getByTitle('Place environment asset (P)').click();
await page.waitForTimeout(400);
report.assetPicker = await page.getByText('Environment asset', { exact: false }).count();
await page.getByText('Redwood', { exact: true }).first().click();
const canvas = page.locator('canvas').first();
const box = await canvas.boundingBox();
await page.mouse.click(box.x + box.width * 0.55, box.y + box.height * 0.58);
await page.waitForTimeout(1500);
await page.mouse.click(box.x + box.width * 0.48, box.y + box.height * 0.62);
await page.waitForTimeout(1500);
report.after = await readObjects();
const consoleText = await page.locator('body').innerText();
report.log = consoleText.match(/Asset edit committed[^\n]*/)?.[0] ?? 'none';
report.toast = consoleText.match(/Placement rejected[^\n]*/)?.[0] ?? 'none';
await shot('reports/visual/ui-asset-placement.jpg');
await page.getByTitle('Remove environment assets (E)').click();
await page.waitForTimeout(300);
await page.mouse.click(box.x + box.width * 0.55, box.y + box.height * 0.58);
await page.waitForTimeout(1500);
report.afterErase = await readObjects();
report.eraseLog = (await page.locator('body').innerText()).match(/Removed \d+ environment asset[^\n]*/)?.[0] ?? 'none';
console.log(JSON.stringify(report, null, 1));
console.log('ERRORS', errors.length ? errors.join('\n') : 'none');
await browser.close();
