import { chromium } from 'playwright';
import fs from 'node:fs';
const b = await chromium.launch({ args: ['--use-angle=swiftshader','--enable-unsafe-swiftshader'] });
const p = await b.newPage({ viewport: { width: 1440, height: 900 } });
const errs = []; p.on('pageerror', e => errs.push(e.message));
p.on('console', m => { if (m.type() === 'error') errs.push(m.text().slice(0,300)); });
await p.goto('http://localhost:4173', { waitUntil: 'load' });
await p.waitForTimeout(12000);
await p.locator('select[aria-label="Render quality"]').selectOption('high');
await p.waitForTimeout(2500);
const c = await p.context().newCDPSession(p);
const { data } = await c.send('Page.captureScreenshot', { format: 'jpeg', quality: 88 });
fs.writeFileSync('reports/visual/v2-sky-fixed.jpg', Buffer.from(data, 'base64'));
await p.locator('select[aria-label="Environment preset"]').selectOption('tropical');
await p.waitForTimeout(2000);
const t = await c.send('Page.captureScreenshot', { format: 'jpeg', quality: 88 });
fs.writeFileSync('reports/visual/v2-tropical.jpg', Buffer.from(t.data, 'base64'));
console.log('errors', errs.length ? errs : 'none');
console.log('footer', (await p.locator('footer').innerText()).replace(/\n/g,' | ').slice(0,240));
await b.close();
