import { chromium } from 'playwright';
import fs from 'node:fs';
const browser = await chromium.launch({ args: ['--use-angle=swiftshader','--enable-unsafe-swiftshader'] });
const page = await browser.newPage({ viewport: { width: 1200, height: 800 } });
await page.goto('http://localhost:4173', { waitUntil: 'load' });
await page.waitForTimeout(12000);
await page.locator('select[aria-label="Render quality"]').selectOption('low');
await page.waitForTimeout(1500);
const client = await page.context().newCDPSession(page);
const shot = async (n) => { const { data } = await client.send('Page.captureScreenshot', { format: 'jpeg', quality: 80 }); fs.writeFileSync(`reports/visual/diag-${n}.jpg`, Buffer.from(data, 'base64')); };
await page.getByText('Layers', { exact: true }).first().click();
await page.waitForTimeout(700);
const flip = async (label) => { const btn = page.locator(`button[role="switch"][aria-label="${label}"]`).first(); if (await btn.count()) { await btn.click(); await page.waitForTimeout(1400); return true; } return false; };
await shot('1-all-on');
console.log('clouds', await flip('Atmospheric clouds')); await shot('2-no-clouds');
console.log('waves', await flip('Animated waves'));
console.log('water', await flip('Ocean & lake surfaces')); await shot('3-no-water');
console.log('bloom', await flip('Bloom & grade')); await shot('4-no-bloom');
console.log('done');
await browser.close();
